export interface KanjiWord { before: string; reading: string; after: string }

export function parseWord(kanji: string): KanjiWord {
  const m = KANJI_WORDS[kanji]?.match(/^(.*)\[(.+)\](.*)$/);
  if (!m) throw new Error(`no word for ${kanji}`);
  return { before: m[1], reading: m[2], after: m[3] };
}
